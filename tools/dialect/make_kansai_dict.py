UON_MAX = -13.0
A_TO_O = dict(zip("アカガサザタダナハバパマヤラワ", "オコゴソゾトドノホボポモヨロオ"))
O_ROW = set("オコゴソゾトドノホボポモヨロ")


def hira2kata(s):
    return "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)


def main():
    dic, out = sys.argv[1], sys.argv[2]
    shift = float(sys.argv[3]) if len(sys.argv) > 3 else 0.0
    rows = {}
    for word, ruby, cid, v, item in CHUNKS:
        rows[(word, hira2kata(ruby))] = (cid, min(-5.0, v + shift), f"{SRC} (大阪弁・京言葉の「{item}」)")
    # ウ音便 (買うた・思うた・手伝うた): 五段ワ行の 連用タ接続 (829, 買っ) と 基本形 (817, 買う) が両方ある語
    base = {}
    renyo = []
    for line in open(dic, encoding="utf-8"):
        r, w, lc, rc, mid, v = line.rstrip("\n").split("\t")
        if lc != rc:
            continue
        if lc == "817" and r.endswith("ウ") and w.endswith("う"):
            base[(r[:-1], w[:-1])] = max(float(v), base.get((r[:-1], w[:-1]), -99))
        elif lc == "829" and r.endswith("ッ") and w.endswith("っ"):
            renyo.append((r[:-1], w[:-1], float(v)))
    n = 0
    for stem_r, stem_w, v in renyo:
        if (stem_r, stem_w) not in base or v < -9.0 or not stem_r:
            continue
        last = stem_r[-1]
        if last in A_TO_O:
            kr = stem_r[:-1] + A_TO_O[last] + "ウ"
        elif last in O_ROW:
            kr = stem_r + "ウ"
        else:
            continue
        key = (stem_w + "う", kr)
        if key not in rows:
            # 2026-11-07: ウ音便の形は、辞書だけの変換で同じ読みや読みの頭が同じ名詞 (肯定・鉄道・王手) に勝った (一般の文 3,675) ので、
            # ふつうの名詞より下の値 (UON_MAX = -13.0 まで) にする
            rows[key] = (829, min(UON_MAX, v - 1.0 + shift), f"{SRC} (大阪弁・京言葉の「買う+た」「思う+た」のウ音便。手本は azooKey の辞書の {stem_w}っ)")
            n += 1
    with open(out, "w", encoding="utf-8") as f:
        f.write("# HaniWord の方言の言い方の辞書 (関西)。設定の「方言の語尾: 関西」を選んだ人だけ読む。tools/dialect/make_kansai_dict.py で作る\n"
                "# 形の出典: ウィキペディア日本語版「日本語の方言の比較表」https://ja.wikipedia.org/w/index.php?oldid=110668082 (2026-08-16 の版、CC BY-SA 4.0)\n"
                "# の大阪弁・京言葉の列。ウ音便の語 (買う (こう)・手伝う (てつどう)) の表記は azooKey の辞書 (Apache License 2.0) の五段ワ行の動詞から\n"
                "# 表記\t読み\t品詞\t意味\t値\t出典\n")
        for (word, ruby), (cid, v, src) in sorted(rows.items(), key=lambda x: x[0][1]):
            f.write(f"{word}\t{ruby}\t{cid}\t501\t{v:.3f}\t{src}\n")
    print(len(rows), "rows (ウ音便", n, ")")


main()
