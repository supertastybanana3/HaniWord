"""2026-11-07 C: 仕事 43・44 (2026-11-07 09:48・10:01 の決め)。閲覧数の上位の記事を、カテゴリで機械で分ける。
(A) 固有名詞 (仕事 44 の常に効く表): 人物 (存命人物・N年生・N年没)・作品 (テレビドラマ・アニメ・映画・漫画・小説・特撮・舞台・楽曲・シングル・アルバム・ゲーム・番組・作品)・
    団体 (音楽グループ・企業・会社・球団・チーム・団体・政党・ユニット・バンド)・出来事 (事件・事故・災害・地震・台風・選挙・戦争・大会・オリンピック)・
    地名と施設 (市・町・村・区・都道府県・国・駅・空港・山・川・島・城・寺・神社・駅・道路・鉄道路線・施設)
(B) ふつうの語 (仕事 43 の表とスイッチ): (A) のどれにも当たらず、カテゴリに 言葉・語・スラング・流行語・ミーム・用語・俗語・概念・表現 があるもの
決まらない: どちらにも当たらないもの (見せて決める)
出力 TSV: 題<TAB>区分<TAB>当たったカテゴリ<TAB>上位の月の数<TAB>直近 12 か月の上位の月<TAB>いちばん多かった月<TAB>その月の閲覧<TAB>転送の行き先
使い方: python3 -I classify_ab.py <top_articles.tsv> <categories.jsonl> <out.tsv>"""
import json, re, sys
top_p, cat_p, out_p = sys.argv[1:4]
RULES = [
    ("A 人物", r"^(存命人物|\d+年生|\d+年没|.*(俳優|女優|歌手|タレント|声優|アイドル|政治家|選手|芸人|YouTuber|漫画家|作家|監督))$"),
    ("A 作品", r"(テレビドラマ|テレビアニメ|アニメ映画|映画|漫画|小説|特撮|舞台作品|楽曲|シングル|アルバム|ゲーム|番組|ライトノベル|ミュージカル)"),
    ("A グループ", r"(音楽グループ|バンド$|ユニット$|アイドルグループ|お笑いコンビ|お笑いトリオ|お笑いグループ|ボーカルグループ|ダンスグループ)"),
    ("A 団体", r"(の企業$|の会社$|球団$|チーム$|団体$|政党$|クラブ$)"),
    ("A 出来事", r"(事件|事故|災害|地震|台風|選挙|戦争|大会|オリンピック|ワールドカップ|紛争)"),
    ("A 地名と施設", r"(の市$|の町$|の村$|の区$|都道府県|の国$|駅$|空港|山$|川$|島$|城$|寺院|神社|道路|鉄道路線|施設|建築物)"),
]
B_RULE = r"(言葉|の語$|語$|スラング|流行語|ミーム|用語|俗語|概念|表現)"
cats = {}
for l in open(cat_p, encoding="utf-8"):
    r = json.loads(l); cats[r["title"]] = r
with open(out_p, "w", encoding="utf-8") as f:
    f.write("# 題\t区分\t当たったカテゴリ\t上位の月の数\t直近 12 か月の上位の月\tいちばん多かった月\tその月の閲覧\t転送の行き先\n")
    for l in open(top_p, encoding="utf-8"):
        if l.startswith("#"): continue
        c = l.rstrip("\n").split("\t"); t = c[0]
        r = cats.get(t)
        if r is None: k, hit = "カテゴリ未取得", ""
        elif not r["exists"]: k, hit = "記事が無い", ""
        else:
            k, hit = "決まらない", ""
            for name, pat in RULES:
                h = [x for x in r["categories"] if re.search(pat, x)]
                if h: k, hit = name, h[0]; break
            if k == "決まらない":
                h = [x for x in r["categories"] if re.search(B_RULE, x)]
                if h: k, hit = "B ふつうの語", h[0]
        f.write("\t".join([t, k, hit, c[1], c[6], c[4], c[5], (r or {}).get("redirect_to", "")]) + "\n")
